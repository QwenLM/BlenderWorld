def score_dimensions(
    obj: dict[str, Any] | None,
    dimensions: list[dict[str, Any]],
) -> dict[str, Any]:
    """Parse the dimension-judge output into normalized scores and flags."""
    result: dict[str, Any] = {
        "ok": False,
        "error": "",
        "dimension_scores": [],
        "dimension_score_0_100": 0.0,
        "core_objects_recognizable": None,
        "catastrophic_failure": None,
        "missing_dimensions": [],
    }
    if not obj:
        result["error"] = "dimension output was not valid JSON"
        return result
    raw = obj.get("dimensions")
    if not isinstance(raw, list):
        result["error"] = "missing dimensions list"
        return result

    by_id: dict[str, dict[str, Any]] = {}
    for item in raw:
        if not isinstance(item, dict):
            continue
        did = str(item.get("id", "")).strip()
        if not did:
            continue
        try:
            score = int(round(float(item.get("score"))))
        except (TypeError, ValueError):
            continue
        if score < 1 or score > 10:
            score = max(1, min(10, score))
        by_id[did] = {
            "id": did,
            "score": score,
            "reasons": str(item.get("reasons", "")).strip(),
            "issues": item.get("issues") if isinstance(item.get("issues"), list) else [],
        }

    scores: list[dict[str, Any]] = []
    missing: list[str] = []
    total = 0
    for dim in dimensions:
        did = str(dim.get("id", "")).strip()
        row = by_id.get(did)
        if row is None:
            missing.append(did)
            scores.append({"id": did, "score": 0, "reasons": "", "issues": [], "missing": True})
        else:
            row["name"] = dim.get("name")
            scores.append(row)
            total += row["score"]

    denom = 10 * len(dimensions)
    result.update(
        {
            "ok": not missing,
            "error": "missing dimensions: " + ", ".join(missing) if missing else "",
            "dimension_scores": scores,
            "dimension_score_0_100": (100.0 * total / denom) if denom else 0.0,
            "core_objects_recognizable": bool(obj.get("core_objects_recognizable"))
            if obj.get("core_objects_recognizable") is not None else None,
            "catastrophic_failure": bool(obj.get("catastrophic_failure"))
            if obj.get("catastrophic_failure") is not None else None,
            "missing_dimensions": missing,
        }
    )
    return result


def normalize_scores(obj: dict[str, Any] | None, rubrics: list[dict[str, Any]]) -> tuple[bool, list[dict[str, Any]], str]:
    if not obj:
        return False, [], "model output was not valid JSON"
    raw_scores = obj.get("rubric_scores")
    if not isinstance(raw_scores, list):
        return False, [], "missing rubric_scores list"

    by_id: dict[str, dict[str, Any]] = {}
    for item in raw_scores:
        if not isinstance(item, dict):
            continue
        rid = str(item.get("id", "")).strip()
        if not rid:
            continue
        score = item.get("score")
        if score in ("0", "0.0"):
            score = 0
        elif score in ("1", "1.0"):
            score = 1
        if score not in (0, 1):
            continue
        by_id[rid] = {
            "id": rid,
            "score": int(score),
            "evidence": str(item.get("evidence", "")).strip(),
            "source_views": item.get("source_views") if isinstance(item.get("source_views"), list) else [],
            "confidence": str(item.get("confidence", "medium")).strip() or "medium",
        }

    normalized = []
    missing = []
    for rubric in rubrics:
        rid = str(rubric.get("id", "")).strip()
        if rid in by_id:
            normalized.append(by_id[rid])
        else:
            missing.append(rid)
    if missing:
        return False, normalized, f"missing scores for ids: {missing[:10]}"
    return True, normalized, ""


def build_score_summary(rubrics: list[dict[str, Any]], scores: list[dict[str, Any]]) -> dict[str, Any]:
    score_by_id = {str(item.get("id")): int(item.get("score", 0)) for item in scores}
    raw_pass = 0
    raw_total = 0
    weighted_pass = 0.0
    weighted_total = 0.0
    missing_scores: list[str] = []
    extra_scores = sorted(set(score_by_id) - {str(r.get("id")) for r in rubrics})

    by_category: dict[str, dict[str, float]] = {}
    by_importance: dict[str, dict[str, float]] = {}

    for rubric in rubrics:
        rid = str(rubric.get("id", "")).strip()
        raw_total += 1
        if rid in score_by_id:
            score = 1 if score_by_id[rid] else 0
        else:
            score = 0
            missing_scores.append(rid)
        raw_pass += score

        weight = float(rubric.get("importance_weight") or 1)
        weighted_pass += score * weight
        weighted_total += weight

        for table, key in (
            (by_category, str(rubric.get("category") or rubric.get("category_v2") or "unknown")),
            (by_importance, str(rubric.get("importance") or "unknown")),
        ):
            row = table.setdefault(
                key,
                {"raw_pass": 0.0, "raw_total": 0.0, "weighted_pass": 0.0, "weighted_total": 0.0},
            )
            row["raw_pass"] += score
            row["raw_total"] += 1
            row["weighted_pass"] += score * weight
            row["weighted_total"] += weight

    def finalize(table: dict[str, dict[str, float]]) -> dict[str, dict[str, float]]:
        out: dict[str, dict[str, float]] = {}
        for key, row in sorted(table.items()):
            raw_total_row = row["raw_total"]
            weighted_total_row = row["weighted_total"]
            out[key] = {
                **row,
                "raw_score_0_100": (100.0 * row["raw_pass"] / raw_total_row) if raw_total_row else 0.0,
                "weighted_score_0_100": (
                    100.0 * row["weighted_pass"] / weighted_total_row
                ) if weighted_total_row else 0.0,
            }
        return out

    return {
        "raw_pass": raw_pass,
        "raw_total": raw_total,
        "raw_score_0_100": (100.0 * raw_pass / raw_total) if raw_total else 0.0,
        "weighted_pass": weighted_pass,
        "weighted_total": weighted_total,
        "weighted_score_0_100": (100.0 * weighted_pass / weighted_total) if weighted_total else 0.0,
        "missing_scores": missing_scores,
        "extra_scores": extra_scores,
        "by_category": finalize(by_category),
        "by_importance": finalize(by_importance),
    }


def atomic_write_json(path: Path, obj: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(obj, ensure_ascii=False, indent=2), encoding="utf-8")
    tmp.replace(path)


async def judge_one(result: dict[str, Any], cfg: dict[str, Any], api_sem: asyncio.Semaphore) -> dict[str, Any]:
    task_dir = Path(result["task_dir"]).resolve()
    rubrics = result.get("rubrics") or []
    rubric_ids = {str(item.get("id")) for item in rubrics}
    out_path = output_path(task_dir, cfg["output_dir"])

    # --- evidence_type routing: scene_summary → agent-as-judge verdicts, {either,render} → VLM ---
    # When routing is off, vlm_rubrics == rubrics and agent_scored is empty, so the code path below
    # is byte-for-byte identical to the non-routed behavior.
    routing = bool(cfg.get("evidence_routing"))
    agent_scored: dict[str, int] = {}
    if routing:
        vlm_types = cfg.get("vlm_evidence_types") or {"either", "render"}
        try:
            agent_verdicts = load_agent_verdicts(
                task_dir, cfg.get("agent_verdict_dir") or "evaluation/agent_judge_multiview_eval"
            )
        except AgentContentRefusal as exc:
            obj = {
                "task_dir": str(task_dir), "ok": False, "error": str(exc),
                "rubric_scores": [], "output_path": str(out_path),
            }
            atomic_write_json(out_path, obj)
            return obj
        vlm_rubrics: list[dict[str, Any]] = []
        fallback_ss = 0
        for item in rubrics:
            ev = str(item.get("evidence_type") or "").strip().lower()
            rid = str(item.get("id"))
            if ev in vlm_types:
                vlm_rubrics.append(item)
            elif rid in agent_verdicts:
                agent_scored[rid] = agent_verdicts[rid]
            else:
                obj = {"task_dir": str(task_dir), "ok": False,
                       "error": f"missing structural verdict: {rid}", "rubric_scores": []}
                atomic_write_json(out_path, obj)
                return obj
        log.info(
            "[evidence-routing] task=%s total=%d vlm=%d agent_scene_summary=%d fallback_to_vlm=%d",
            task_name(task_dir), len(rubrics), len(vlm_rubrics), len(agent_scored), fallback_ss,
        )
    else:
        vlm_rubrics = rubrics

    if not cfg["overwrite"] and is_complete_judgement(out_path, rubric_ids):
        existing = json.loads(out_path.read_text(encoding="utf-8"))
        existing["skipped_existing"] = True
        score_summary = build_score_summary(rubrics, existing.get("rubric_scores") or [])
        existing.update(score_summary)
        return existing

    render_images = find_render_images(task_dir, cfg["image_glob"], cfg["max_images"])
    extra_images = find_extra_submission_images(
        task_dir,
        cfg["extra_image_glob"],
        cfg["max_extra_images"],
    )
    anim_frames = find_animation_frames(
        task_dir,
        cfg["anim_frame_glob"],
        cfg["max_anim_frames"],
    )
    images = dedupe_paths(render_images + extra_images)
    reference_images = [] if cfg["no_reference_images"] else find_reference_images(
        task_dir,
        cfg["reference_image_glob"],
        cfg["max_reference_images"],
    )
    if cfg["dry_run"]:
        obj = {
            "created_at": datetime.now(timezone.utc).isoformat(),
            "task_dir": str(task_dir),
            "output_path": str(out_path),
            "reference_image_files": [rel(path, task_dir) for path in reference_images],
            "image_files": [rel(path, task_dir) for path in images],
            "rendered_image_files": [rel(path, task_dir) for path in render_images],
            "extra_image_files": [rel(path, task_dir) for path in extra_images],
            "anim_frame_files": [rel(path, task_dir) for path in anim_frames],
            "rubric_count": len(rubrics),
            "ok": True,
            "dry_run": True,
            "rubric_scores": [],
        }
        atomic_write_json(out_path, obj)
        return obj

    if not render_images:
        obj = {
            "created_at": datetime.now(timezone.utc).isoformat(),
            "task_dir": str(task_dir),
            "output_path": str(out_path),
            "ok": False,
            "error": f"no evaluator renders matched {cfg['image_glob']}",
            "rubric_count": len(rubrics),
            "rubric_scores": [],
        }
        atomic_write_json(out_path, obj)
        return obj

    submission_image_groups = [
        (
            "Group A - evaluator-generated multi-view renders from the submitted .blend",
            "Middle-layer multi-view render",
            render_images,
        ),
        (
            "Group B - upstream exported images produced alongside the same .blend artifact",
            "Upstream .blend co-produced image",
            extra_images,
        ),
    ]
    # Animation/video tasks only: a third, time-ordered group so motion/timing
    # rubrics are judged on the actual sequence instead of auto-failed on stills.
    if anim_frames:
        submission_image_groups.append((
            "Group C - time-ordered frames sampled from the model's OWN exported animation video (first -> last)",
            "Animation frame (time-ordered)",
            anim_frames,
        ))
    submission_caption = (
        "Submitted image evidence to score. Group A images are middle-layer "
        "Claude/Sonnet multi-view renders from the submitted .blend. Group B "
        "images are upstream PNGs produced alongside that same .blend artifact. "
        "Group C (when present) are time-ordered frames sampled from the model's "
        "own exported animation video — read them as a sequence for motion/timing. "
        "Consider all provided groups together, using the group labels when citing evidence:"
    )

    render_blind = None
    reference_blind = None
    if cfg["blind_pass"]:
        blind_calls = [
            describe_blind(
                image_paths=images,
                model=cfg["model"],
                api_key=cfg["api_key"],
                max_tokens=cfg["blind_max_tokens"],
                timeout=cfg["timeout"],
                retries=cfg["retries"],
                sem=api_sem,
                image_detail=cfg["image_detail"],
                api_endpoint=cfg["api_endpoint"],
                user_text=BLIND_USER,
                caption=(
                    "Submission images to describe. Group A images are "
                    "evaluator-generated multi-view renders from the "
                    "submitted .blend. Group B images are upstream PNGs produced "
                    "alongside that same .blend artifact:"
                ),
                image_groups=submission_image_groups,
                label_root=task_dir,
            )
        ]
        if reference_images:
            blind_calls.append(
                describe_blind(
                    image_paths=reference_images,
                    model=cfg["model"],
                    api_key=cfg["api_key"],
                    max_tokens=cfg["blind_max_tokens"],
                    timeout=cfg["timeout"],
                    retries=cfg["retries"],
                    sem=api_sem,
                    image_detail=cfg["image_detail"],
                    api_endpoint=cfg["api_endpoint"],
                    user_text=BLIND_USER_REF,
                    caption="Reference image(s) to describe:",
                )
            )
        blind_results = await asyncio.gather(*blind_calls)
        render_blind = blind_results[0]
        if reference_images:
            reference_blind = blind_results[1]

    render_blind_block = (render_blind or "").strip() or (
        "(blind description unavailable; judge the renders on their own visual evidence)"
    )
    reference_blind_block = (reference_blind or "").strip() or (
        "(no reference image provided; nothing to compare against)"
    )

    dimension_user_text = DIMENSION_USER_TEMPLATE.format(
        prompt=result.get("prompt", ""),
        reference_names=(
            "\n".join(f"- reference_{idx + 1}: {rel(path, task_dir)}" for idx, path in enumerate(reference_images))
            if reference_images else
            "(no reference images found)"
        ),
        view_names=render_submission_inventory(task_dir, render_images, extra_images, anim_frames),
        blind_description=render_blind_block,
        blind_reference_description=reference_blind_block,
        dimensions=render_dimensions(DIMENSIONS),
    )

    chunk_size = int(cfg.get("rubric_batch_size") or 0)
    chunks = rubric_chunks(vlm_rubrics, chunk_size)
    if routing and not vlm_rubrics:
        # All rubrics resolved from agent verdicts — skip the VLM rubric pass entirely
        # (dimension pass, when enabled, still runs below).
        chunks = []
    rubric_calls = []
    for idx, chunk in enumerate(chunks, start=1):
        user_text = build_rubric_user_text(
            result=result,
            task_dir=task_dir,
            reference_images=reference_images,
            render_images=render_images,
            extra_images=extra_images,
            blind_description=render_blind_block,
            blind_reference_description=reference_blind_block,
            rubrics=chunk,
            anim_frames=anim_frames,
        )
        rubric_calls.append(
            call_json_gpt55(
                user_text=user_text,
                reference_image_paths=reference_images,
                rendered_image_paths=images,
                model=cfg["model"],
                api_key=cfg["api_key"],
                max_tokens=cfg["max_tokens"],
                timeout=cfg["timeout"],
                retries=cfg["retries"],
                json_retries=cfg["json_retries"],
                sem=api_sem,
                image_detail=cfg["image_detail"],
                api_endpoint=cfg["api_endpoint"],
                validate=lambda obj, chunk=chunk: validate_rubric_json(obj, chunk),
                rendered_caption=submission_caption,
                label_root=task_dir,
                rendered_image_groups=submission_image_groups,
                kind=(
                    f"rubric judge chunk {idx}/{len(chunks)}"
                    if len(chunks) > 1 else
                    "rubric judge"
                ),
            )
        )

    judge_calls = [
        *rubric_calls,
    ]
    if cfg["dimension_pass"]:
        judge_calls.append(
            call_json_gpt55(
                user_text=dimension_user_text,
                reference_image_paths=reference_images,
                rendered_image_paths=images,
                model=cfg["model"],
                api_key=cfg["api_key"],
                max_tokens=cfg["dimension_max_tokens"],
                timeout=cfg["timeout"],
                retries=cfg["retries"],
                json_retries=cfg["json_retries"],
                sem=api_sem,
                image_detail=cfg["image_detail"],
                api_endpoint=cfg["api_endpoint"],
                validate=validate_dimension_json,
                system_prompt=DIMENSION_SYSTEM,
                rendered_caption=submission_caption,
                label_root=task_dir,
                rendered_image_groups=submission_image_groups,
                kind="dimension judge",
            )
        )
    judge_results = await asyncio.gather(*judge_calls)

    chunk_results = judge_results[:len(rubric_calls)]
    combined_scores: list[dict[str, Any]] = []
    combined_notes: list[str] = []
    combined_raw: list[str | None] = []
    chunk_errors: list[str] = []
    chunk_meta: list[dict[str, Any]] = []
    for idx, (chunk, chunk_result) in enumerate(zip(chunks, chunk_results), start=1):
        raw_chunk, parsed_chunk, meta_chunk = chunk_result
        combined_raw.append(raw_chunk)
        ok_chunk, scores_chunk, error_chunk = normalize_scores(parsed_chunk, chunk)
        combined_scores.extend(scores_chunk)
        notes = str((parsed_chunk or {}).get("overall_notes", "")).strip()
        if notes:
            combined_notes.append(f"chunk {idx}: {notes}")
        meta = {
            **meta_chunk,
            "chunk_index": idx,
            "chunk_count": len(chunks),
            "rubric_ids": [str(item.get("id")) for item in chunk],
            "ok": ok_chunk,
        }
        if error_chunk:
            meta["error"] = error_chunk
            chunk_errors.append(f"chunk {idx}: {error_chunk}")
        chunk_meta.append(meta)

    # Merge scene_summary verdicts from the agent-as-judge pass into the combined scores.
    # These ids are excluded from vlm_rubrics, so there is no collision with VLM output.
    for rid, agent_score in agent_scored.items():
        combined_scores.append({
            "id": rid,
            "score": int(agent_score),
            "evidence": "agent-as-judge verdict (evidence_type=scene_summary)",
            "source_views": [],
            "confidence": "high",
            "method": "agent",
        })

    parsed = {
        "rubric_scores": combined_scores,
        "overall_notes": "\n".join(combined_notes),
    }
    raw = "\n\n".join(raw for raw in combined_raw if raw)
    rubric_json_meta = {
        "kind": "rubric judge",
        "chunked": len(chunks) > 1,
        "rubric_batch_size": chunk_size,
        "chunk_count": len(chunks),
        "json_ok": not chunk_errors,
        "chunks": chunk_meta,
    }
    if chunk_errors:
        rubric_json_meta["errors"] = chunk_errors

    if cfg["dimension_pass"]:
        dim_raw, dim_parsed, dimension_json_meta = judge_results[len(rubric_calls)]
    else:
        dim_raw, dim_parsed, dimension_json_meta = None, None, None

    ok, scores, error = normalize_scores(parsed, rubrics)
    if chunk_errors and not error:
        error = "; ".join(chunk_errors)
    total = sum(item["score"] for item in scores)
    max_score = len(rubrics)
    score_summary = build_score_summary(rubrics, scores)

    # --- dimension scoring + uncapped 50/50 fusion ---
    rubric_score_0_100 = score_summary["weighted_score_0_100"]
    dim_result = score_dimensions(dim_parsed, DIMENSIONS) if cfg["dimension_pass"] else None
    if cfg["dimension_pass"] and (not dim_result or not dim_result["ok"]):
        ok = False
        error = "; ".join(x for x in [error, "dimension judge failed"] if x)

    w = cfg["dimension_weight"]
    if dim_result and dim_result["ok"]:
        dimension_score_0_100 = dim_result["dimension_score_0_100"]
        fused_score_0_100 = w * dimension_score_0_100 + (1.0 - w) * rubric_score_0_100
    else:
        dimension_score_0_100 = None
        fused_score_0_100 = rubric_score_0_100  # fall back to rubric-only

    cap_applied = False
    cap_reason = ""

    obj = {
        "created_at": datetime.now(timezone.utc).isoformat(),
        "task_dir": str(task_dir),
        "output_path": str(out_path),
        "model": cfg["model"],
        "reference_image_files": [rel(path, task_dir) for path in reference_images],
        "image_files": [rel(path, task_dir) for path in images],
        "rendered_image_files": [rel(path, task_dir) for path in render_images],
        "extra_image_files": [rel(path, task_dir) for path in extra_images],
        "rubric_count": len(rubrics),
        "score": total,
        "max_score": max_score,
        "normalized_score": (total / max_score) if max_score else 0.0,
        "raw_pass": score_summary["raw_pass"],
        "raw_total": score_summary["raw_total"],
        "raw_score_0_100": score_summary["raw_score_0_100"],
        "weighted_pass": score_summary["weighted_pass"],
        "weighted_total": score_summary["weighted_total"],
        "weighted_score_0_100": score_summary["weighted_score_0_100"],
        "score_summary": score_summary,
        "passed_count": total,
        "failed_count": max_score - total,
        "rubric_scores": scores,
        "overall_notes": str((parsed or {}).get("overall_notes", "")).strip(),
        "blind_pass": cfg["blind_pass"],
        "blind_description": render_blind,
        "blind_reference_description": reference_blind,
        "rubric_batch_size": chunk_size,
        "rubric_chunk_count": len(chunks),
        # --- holistic dimension scoring + fusion ---
        "dimension_pass": cfg["dimension_pass"],
        "dimension_weight": w,
        "rubric_score_0_100": rubric_score_0_100,
        "dimension_score_0_100": dimension_score_0_100,
        "fused_score_0_100": fused_score_0_100,
        "cap_applied": cap_applied,
        "cap_reason": cap_reason,
        "dimension_scores": (dim_result or {}).get("dimension_scores", []),
        "core_objects_recognizable": (dim_result or {}).get("core_objects_recognizable"),
        "catastrophic_failure": (dim_result or {}).get("catastrophic_failure"),
        "dimension_missing": (dim_result or {}).get("missing_dimensions", []),
        "dimension_notes": str((dim_parsed or {}).get("overall_notes", "")).strip(),
        "json_repair": rubric_json_meta,
        "dimension_json_repair": dimension_json_meta,
        "ok": ok,
    }
    if routing:
        obj["evidence_routing"] = True
        obj["agent_scored_ids"] = sorted(agent_scored)
    if dim_result and not dim_result["ok"]:
        obj["dimension_error"] = dim_result.get("error", "")
    if not ok:
        obj["error"] = error
        obj["raw_output"] = raw
    if cfg["save_raw"]:
        if raw is not None:
            obj["raw_output"] = raw
        if dim_raw is not None:
            obj["dimension_raw_output"] = dim_raw
    atomic_write_json(out_path, obj)
    return obj


async def run_all(results: list[dict[str, Any]], cfg: dict[str, Any]) -> list[dict[str, Any]]:
    api_sem = asyncio.Semaphore(cfg["concurrency"])
    task_sem = asyncio.Semaphore(cfg["task_concurrency"])
    done = {"n": 0, "fail": 0, "skip": 0}
    outputs: list[dict[str, Any]] = []

    async def worker(item: dict[str, Any]) -> None:
        async with task_sem:
            out = await judge_one(item, cfg, api_sem)
            outputs.append(out)
            done["n"] += 1
            if out.get("skipped_existing"):
                done["skip"] += 1
            if not out.get("ok"):
                done["fail"] += 1
            log.info(
                "task=%s ok=%s rubric=%s/%s rubric100=%.1f dim100=%s fused=%.1f%s progress=%d/%d skipped=%d failed=%d",
                Path(item["task_dir"]).name,
                out.get("ok"),
                out.get("score"),
                out.get("max_score"),
                float(out.get("rubric_score_0_100") or out.get("weighted_score_0_100") or 0.0),
                ("%.1f" % out["dimension_score_0_100"]) if isinstance(out.get("dimension_score_0_100"), (int, float)) else "NA",
                float(out.get("fused_score_0_100") or 0.0),
                " CAP" if out.get("cap_applied") else "",
                done["n"],
                len(results),
                done["skip"],
                done["fail"],
            )

    await asyncio.gather(*(worker(item) for item in results))
    return outputs


def build_batch_score_summary(outputs: list[dict[str, Any]]) -> dict[str, Any]:
    scored = [item for item in outputs if item.get("ok") and "weighted_score_0_100" in item]
    raw_pass = sum(float(item.get("raw_pass", item.get("score", 0))) for item in scored)
    raw_total = sum(float(item.get("raw_total", item.get("max_score", 0))) for item in scored)
    weighted_pass = sum(float(item.get("weighted_pass", 0.0)) for item in scored)
    weighted_total = sum(float(item.get("weighted_total", 0.0)) for item in scored)
    return {
        "scoring_method": (
            "weighted_score_0_100=100*sum(binary_score*importance_weight)/sum(importance_weight); "
            "raw_score_0_100=100*sum(binary_score)/rubric_count"
        ),
        "scored_task_count": len(scored),
        "raw_pass": raw_pass,
        "raw_total": raw_total,
        "raw_micro_score_0_100": (100.0 * raw_pass / raw_total) if raw_total else 0.0,
        "weighted_pass": weighted_pass,
        "weighted_total": weighted_total,
        "weighted_micro_score_0_100": (100.0 * weighted_pass / weighted_total) if weighted_total else 0.0,
        "raw_macro_score_0_100": (
            sum(float(item.get("raw_score_0_100", 0.0)) for item in scored) / len(scored)
        ) if scored else 0.0,
        "weighted_macro_score_0_100": (
            sum(float(item.get("weighted_score_0_100", 0.0)) for item in scored) / len(scored)
        ) if scored else 0.0,
        "dimension_macro_score_0_100": (
            _mean([item.get("dimension_score_0_100") for item in scored])
        ),
        "fused_macro_score_0_100": (
            _mean([item.get("fused_score_0_100") for item in scored])
        ),
        "cap_applied_count": sum(1 for item in scored if item.get("cap_applied")),
    }


def _mean(values: list[Any]) -> float | None:
    nums = [float(v) for v in values if isinstance(v, (int, float))]
    return (sum(nums) / len(nums)) if nums else None


