# "Image size exceeds the limit" — a deterministic 400 on full-resolution 4K hero
# PNGs (~37MB) that zeroes the whole judge (rubric_batch_size=0 -> missing scores).
# The upstream limit is ~20MB, so we keep images comfortably under it WITHOUT
# reducing resolution: an image already within budget uploads byte-for-byte
# (untouched, lossless); an oversized one is re-encoded PNG->JPEG at FULL
# resolution and the highest quality that fits (the VLM downsamples to ~1536px
# internally, so full-res JPEG q95 is lossless for judging). Resolution is only
# reduced as an unreachable last resort (full-res q80 still over budget). Tunable
# via JUDGE_MEDIA_OSS_MAX_MB (default 15MB, a safe margin below the ~20MB cap).
_MEDIA_OSS_MAX_IMAGE_BYTES = int(float(os.environ.get("JUDGE_MEDIA_OSS_MAX_MB", "15") or 15) * 1024 * 1024)
_MEDIA_OSS_JPEG_QUALITY_LADDER = (95, 92, 90, 88, 85, 82, 80)
_MEDIA_OSS_LASTRESORT_SCALES = (0.85, 0.7, 0.55, 0.4)
_MEDIA_OSS_NO_DIM_CLAMP = 10_000_000  # effectively disable dimension downscaling on the JPEG path


def _media_oss_config() -> dict[str, str] | None:
    if str(os.environ.get("MEDIA_OSS_ENABLED", "")).strip().lower() not in ("1", "true", "yes", "on"):
        return None
    bucket = os.environ.get("MEDIA_OSS_BUCKET", "").strip()
    endpoint = os.environ.get("MEDIA_OSS_ENDPOINT", "").strip()
    akid = os.environ.get("MEDIA_OSS_ACCESS_KEY_ID", "").strip()
    secret = os.environ.get("MEDIA_OSS_ACCESS_KEY_SECRET", "").strip()
    if not (bucket and endpoint and akid and secret):
        return None
    endpoint = endpoint.replace("https://", "").replace("http://", "").strip("/")
    prefix = os.environ.get("MEDIA_OSS_OBJECT_PREFIX", "").strip().strip("/")
    return {"bucket": bucket, "endpoint": endpoint, "akid": akid, "secret": secret, "prefix": prefix}


def _oss_sign(secret: str, string_to_sign: str) -> str:
    digest = hmac.new(secret.encode("utf-8"), string_to_sign.encode("utf-8"), hashlib.sha1).digest()
    return base64.b64encode(digest).decode("ascii")


def _oss_presigned_get_url(cfg: dict[str, str], key: str, expiry: int = _MEDIA_OSS_URL_EXPIRY_SECONDS) -> str:
    expires = int(time.time()) + expiry
    string_to_sign = f"GET\n\n\n{expires}\n/{cfg['bucket']}/{key}"
    signature = _oss_sign(cfg["secret"], string_to_sign)
    path = urllib.parse.quote(key, safe="/")
    query = urllib.parse.urlencode({"OSSAccessKeyId": cfg["akid"], "Expires": expires, "Signature": signature})
    return f"https://{cfg['bucket']}.{cfg['endpoint']}/{path}?{query}"


def _oss_put_object(cfg: dict[str, str], key: str, data: bytes, content_type: str) -> None:
    date = email.utils.formatdate(timeval=time.time(), usegmt=True)
    string_to_sign = f"PUT\n\n{content_type}\n{date}\n/{cfg['bucket']}/{key}"
    signature = _oss_sign(cfg["secret"], string_to_sign)
    path = urllib.parse.quote(key, safe="/")
    url = f"https://{cfg['bucket']}.{cfg['endpoint']}/{path}"
    headers = {
        "Date": date,
        "Content-Type": content_type,
        "Authorization": f"OSS {cfg['akid']}:{signature}",
    }
    resp = requests.put(url, data=data, headers=headers, timeout=_MEDIA_OSS_PUT_TIMEOUT)
    resp.raise_for_status()


def _media_oss_upload_image(path: Path) -> str | None:
    cfg = _media_oss_config()
    if cfg is None:
        return None
    try:
        raw = path.read_bytes()
    except OSError as exc:
        log.warning("media-oss: cannot read %s: %s", path, exc)
        return None
    if not raw:
        return None

    ext = path.suffix.lower()
    if ext not in _MEDIA_OSS_CONTENT_TYPES:
        ext = ".png"
    data = raw
    # Keep the image under the configured gateway's per-image download limit WITHOUT touching its
    # resolution. In-budget images upload byte-for-byte (untouched, lossless); an
    # oversized one is re-encoded PNG->JPEG at FULL resolution (no downscale except
    # as an unreachable last resort), which turns a ~37MB 4K PNG into a ~5-8MB
    # full-res JPEG the VLM cannot distinguish from the original at its ~1536px
    # working resolution. Falls back to uploading the raw bytes if Pillow is missing
    # or re-encoding fails, so judging still proceeds.
    if len(raw) > _MEDIA_OSS_MAX_IMAGE_BYTES and Image is not None:
        try:
            with Image.open(io.BytesIO(raw)) as im:
                width, height = im.size
                data = _compress_image_to_jpeg_bytes(
                    im,
                    max_bytes=_MEDIA_OSS_MAX_IMAGE_BYTES,
                    max_dim=_MEDIA_OSS_NO_DIM_CLAMP,
                    quality_ladder=_MEDIA_OSS_JPEG_QUALITY_LADDER,
                    scale_ladder=_MEDIA_OSS_LASTRESORT_SCALES,
                )
            ext = ".jpg"
            log.info(
                "media-oss: re-encoded oversized %s (%.1fMB PNG %dx%d) -> %.2fMB full-res JPEG (<=%.0fMB budget)",
                path.name, len(raw) / 1024 / 1024, width, height,
                len(data) / 1024 / 1024, _MEDIA_OSS_MAX_IMAGE_BYTES / 1024 / 1024,
            )
        except Exception as exc:  # noqa: BLE001
            log.warning("media-oss: re-encode failed for %s: %s; uploading original bytes", path, exc)
            data = raw
            ext = path.suffix.lower()
            if ext not in _MEDIA_OSS_CONTENT_TYPES:
                ext = ".png"
    elif len(raw) > _MEDIA_OSS_MAX_IMAGE_BYTES:
        log.warning(
            "media-oss: %s is %.1fMB and Pillow is unavailable; uploading raw (may exceed the limit)",
            path, len(raw) / 1024 / 1024,
        )

    content_type = _MEDIA_OSS_CONTENT_TYPES[ext]
    digest = hashlib.sha1(data).hexdigest()[:24]
    key = "/".join(p for p in (cfg["prefix"], "judge", f"{digest}{ext}") if p)
    retries = max(1, int(os.environ.get("MEDIA_OSS_IMAGE_URL_MAX_RETRIES", "3") or 3))
    if digest not in _media_oss_uploaded_keys:
        last_exc: Exception | None = None
        for _attempt in range(retries):
            try:
                _oss_put_object(cfg, key, data, content_type)
                _media_oss_uploaded_keys.add(digest)
                last_exc = None
                break
            except Exception as exc:  # noqa: BLE001
                last_exc = exc
        if last_exc is not None:
            log.warning(
                "media-oss: upload failed for %s after %d attempt(s): %s; falling back to base64",
                path, retries, last_exc,
            )
            return None
    return _oss_presigned_get_url(cfg, key)


def image_to_attach_url(path: Path, max_bytes: int = MAX_IMAGE_BYTES) -> str | None:
    """Value for image_url.url: a media-OSS pre-signed URL (full-resolution,
    lossless) when media OSS is configured, else an inline base64 data URL.

    Media OSS avoids the configured gateway's request-body cap entirely, so no recompression is
    needed. On any upload failure we fall back to base64 so judging still runs.
    """
    if not path.exists():
        return None
    if _media_oss_config() is not None:
        url = _media_oss_upload_image(path)
        if url:
            return url
        # upload failed -> fall through to base64 so judging still proceeds
    return image_to_data_url(path, max_bytes=max_bytes)


def _iter_image_parts(messages: list[dict[str, Any]]):
    """Yield (content_list, index, part) for every inline data: image_url part."""
    for message in messages:
        content = message.get("content")
        if not isinstance(content, list):
            continue
        for idx, part in enumerate(content):
            if not isinstance(part, dict) or part.get("type") != "image_url":
                continue
            url = (part.get("image_url") or {}).get("url", "")
            if isinstance(url, str) and url.startswith("data:"):
                yield content, idx, part


def _request_body_size(messages: list[dict[str, Any]]) -> int:
    """Approximate the byte size of the eventual POST body.

    call_gpt55 sends ``requests.post(json={"model", "messages", ...})`` which serializes with
    ensure_ascii=True; base64 image data (which dominates the payload) is ASCII so ensure_ascii
    is size-neutral for it. Add a fixed slack for the wrapper keys so the measurement matches
    the Content-Length the configured gateway actually enforces.
    """
    return len(json.dumps({"messages": messages}, ensure_ascii=False).encode("utf-8")) + 8192


def shrink_messages_to_fit(messages: list[dict[str, Any]], max_body: int = MAX_REQUEST_BODY_BYTES) -> list[dict[str, Any]]:
    if next(_iter_image_parts(messages), None) is None:
        return messages

    size = _request_body_size(messages)
    if size <= max_body:
        return messages

    if Image is None:
        log.warning(
            "Pillow unavailable; cannot shrink oversized request body (%.1f MB > %.1f MB cap)",
            size / 1024 / 1024,
            max_body / 1024 / 1024,
        )
        return messages

    log.warning(
        "request body %.1f MB exceeds %.1f MB cap; recompressing %d image(s)",
        size / 1024 / 1024,
        max_body / 1024 / 1024,
        sum(1 for _ in _iter_image_parts(messages)),
    )

    # Iteratively recompress every oversized image, tightening the per-image budget each round
    # until the whole body fits. The per-image budget is derived from the images that remain,
    # so a single pass usually suffices; the loop is a convergence guard for the case where
    # many images already sit below budget and only a few dominate.
    for iteration in range(6):
        parts = [(part, (part.get("image_url") or {}).get("url", "")) for _c, _i, part in _iter_image_parts(messages)]
        n = len(parts)
        if n == 0:
            break
        squeeze = 0.85 ** iteration
        per_image_b64 = max(1, int(((max_body - 8192) // n) * squeeze))
        per_image_raw = max(1, int(per_image_b64 * 3 / 4))
        for part, url in parts:
            _, _, b64_data = url.partition(",")
            try:
                raw = base64.b64decode(b64_data)
                if len(raw) <= per_image_raw:
                    continue
                b64 = _compress_image_to_base64(Image.open(io.BytesIO(raw)), max_bytes=per_image_raw)
                part["image_url"]["url"] = f"data:image/jpeg;base64,{b64}"
            except Exception as exc:  # noqa: BLE001
                log.warning("failed to shrink image in request body: %s", exc)
        size = _request_body_size(messages)
        if size <= max_body:
            log.warning(
                "recompress pass %d -> %.1f MB (under %.1f MB cap)",
                iteration + 1,
                size / 1024 / 1024,
                max_body / 1024 / 1024,
            )
            return messages

    # Recompression alone did not fit (e.g. Pillow could not squeeze far enough). Last resort:
    # drop trailing image_url parts together with their immediately-preceding label text. Images
    # are appended hero-renders/references first and animation-frames/extras last, so trailing
    # drops shed the least-critical frames first.
    dropped = 0
    while size > max_body:
        tail = None
        for content, idx, part in _iter_image_parts(messages):
            tail = (content, idx)
        if tail is None:
            break
        content, idx = tail
        del content[idx]
        if idx - 1 >= 0 and isinstance(content[idx - 1], dict) and content[idx - 1].get("type") == "text":
            del content[idx - 1]
        dropped += 1
        size = _request_body_size(messages)
    if dropped:
        log.warning(
            "dropped %d trailing image(s) to fit request under %.1f MB cap -> %.1f MB",
            dropped,
            max_body / 1024 / 1024,
            size / 1024 / 1024,
        )
    return messages


def rel(path: Path, root: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.resolve().as_posix()


def image_label(path: Path, root: Path | None = None) -> str:
    if root is not None:
        return rel(path, root)
    return path.name


def append_labeled_images(
    content: list[dict[str, Any]],
    paths: list[Path],
    *,
    role: str,
    label_root: Path | None = None,
) -> int:
    attached = 0
    for path in paths:
        url = image_to_attach_url(path)
        if not url:
            continue
        content.append({"type": "text", "text": f"{role} image file: {image_label(path, label_root)}"})
        content.append({"type": "image_url", "image_url": {"url": url}})
        attached += 1
    return attached


def append_labeled_image_groups(
    content: list[dict[str, Any]],
    groups: list[tuple[str, str, list[Path]]],
    *,
    label_root: Path | None = None,
) -> int:
    attached = 0
    for title, role, paths in groups:
        if not paths:
            content.append({"type": "text", "text": f"{title}: (none found)"})
            continue
        content.append({"type": "text", "text": f"{title}:"})
        attached += append_labeled_images(content, paths, role=role, label_root=label_root)
    return attached


def _clean_json(raw: str | None) -> str:
    text = (raw or "").strip()
    if text.startswith("```"):
        text = text.strip("`")
        if text.lower().startswith("json"):
            text = text[4:]
    return text.strip()


def _extract_first_json_object(text: str) -> str | None:
    start = text.find("{")
    if start < 0:
        return None
    depth = 0
    in_string = False
    escape = False
    for idx in range(start, len(text)):
        ch = text[idx]
        if in_string:
            if escape:
                escape = False
            elif ch == "\\":
                escape = True
            elif ch == '"':
                in_string = False
            continue
        if ch == '"':
            in_string = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return text[start: idx + 1]
    return text[start:] if start >= 0 else None


def parse_json_obj(raw: str | None) -> dict[str, Any] | None:
    text = _clean_json(raw)
    candidates = [text]
    extracted = _extract_first_json_object(text)
    if extracted and extracted not in candidates:
        candidates.append(extracted)
    for candidate in candidates:
        for repaired in (candidate, repair_json(candidate)):
            try:
                obj = json.loads(repaired)
            except Exception:
                continue
            if isinstance(obj, dict):
                return obj
    return None


def raw_preview(raw: str | None, limit: int = 1200) -> str:
    text = (raw or "").strip().replace("\r", "")
    return text[:limit] + ("..." if len(text) > limit else "")


def parse_stream_response(response: requests.Response) -> dict[str, Any]:
    result_content = ""
    stop_reason = None
    usage = None
    has_data = False
    for line in response.iter_lines(decode_unicode=True):
        if not line or not line.startswith("data: "):
            continue
        data_str = line[6:].strip()
        if data_str == "[DONE]":
            break
        try:
            chunk = json.loads(data_str)
        except json.JSONDecodeError:
            log.warning("failed to parse stream chunk: %s", data_str[:200])
            continue
        has_data = True
        choices = chunk.get("choices") or []
        if choices:
            delta = choices[0].get("delta") or {}
            content = delta.get("content") or ""
            if content:
                result_content += content
            finish = choices[0].get("finish_reason")
            if finish:
                stop_reason = finish
        if chunk.get("usage"):
            usage = chunk["usage"]
    if not has_data:
        raise ValueError("No chunks in stream response")
    return {
        "choices": [{"message": {"content": result_content}, "finish_reason": stop_reason}],
        "usage": usage,
    }


def post_sync(endpoint: str, api_key: str, body: dict[str, Any], timeout: int) -> dict[str, Any]:
    auth = api_key if api_key.lower().startswith("bearer ") else f"Bearer {api_key}"
    headers = {"Content-Type": "application/json", "Authorization": auth}
    stream = bool(body.get("stream"))
    response = requests.post(endpoint, headers=headers, json=body, timeout=timeout, stream=stream)
    if response.status_code != 200:
        raise requests.HTTPError(f"{response.status_code}: {response.text[:2000]}", response=response)
    if stream:
        return parse_stream_response(response)
    return response.json()


def extract_openai(obj: dict[str, Any]) -> str | None:
    choices = obj.get("choices") if isinstance(obj, dict) else None
    if not choices:
        return None
    return (choices[0].get("message") or {}).get("content")


async def call_gpt55(
    user_text: str,
    reference_image_paths: list[Path],
    rendered_image_paths: list[Path],
    model: str,
    api_key: str,
    max_tokens: int,
    timeout: int,
    retries: int,
    sem: asyncio.Semaphore,
    image_detail: str,
    api_endpoint: str = _DASH_ENDPOINT,
    system_prompt: str = JUDGE_SYSTEM,
    rendered_caption: str = "Submitted rendered multi-view image(s) to score:",
    label_root: Path | None = None,
    rendered_image_groups: list[tuple[str, str, list[Path]]] | None = None,
) -> str | None:
    content: list[dict[str, Any]] = []

    content.append({"type": "text", "text": user_text})
    if reference_image_paths:
        content.append({"type": "text", "text": "Reference image(s) for the target scene:"})
    append_labeled_images(content, reference_image_paths, role="Reference", label_root=label_root)
    content.append({"type": "text", "text": rendered_caption})
    if rendered_image_groups is not None:
        attached_submission_images = append_labeled_image_groups(
            content,
            rendered_image_groups,
            label_root=label_root,
        )
    else:
        attached_submission_images = append_labeled_images(
            content,
            rendered_image_paths,
            role="Submission",
            label_root=label_root,
        )
    if rendered_image_paths and attached_submission_images == 0:
        log.warning("no submission images could be attached after compression/filtering")
        return None
    messages = shrink_messages_to_fit(
        [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": content},
        ]
    )
    body = {
        "model": model,
        "messages": messages,
        "stream": True,
        "reasoning_effort": "xhigh",
        "max_output_tokens": max_tokens,
    }
    for attempt in range(retries):
        async with sem:
            try:
                obj = await asyncio.to_thread(post_sync, api_endpoint, api_key, body, timeout)
                # Counters only: never persist the request, API key or signed URLs.
                usage_log = os.environ.get("JUDGE_USAGE_LOG")
                if usage_log and obj.get("usage"):
                    with open(usage_log, "a", encoding="utf-8") as handle:
                        handle.write(json.dumps({"type": "api_usage", "model": model, "usage": obj["usage"]}) + "\n")
                out = extract_openai(obj)
                if out:
                    return out
                log.warning("empty model output attempt=%d: %s", attempt + 1, json.dumps(obj)[:300])
            except Exception as exc:  # noqa: BLE001
                log.warning("judge call failed attempt=%d: %s", attempt + 1, exc)
        await asyncio.sleep(1 + attempt)
    return None


def validate_rubric_json(obj: dict[str, Any] | None, rubrics: list[dict[str, Any]]) -> str:
    ok, _, error = normalize_scores(obj, rubrics)
    return "" if ok else error


def validate_dimension_json(obj: dict[str, Any] | None) -> str:
    result = score_dimensions(obj, DIMENSIONS)
    return "" if result["ok"] else str(result.get("error") or "invalid dimension JSON")


async def call_json_gpt55(
    *,
    user_text: str,
    reference_image_paths: list[Path],
    rendered_image_paths: list[Path],
    model: str,
    api_key: str,
    max_tokens: int,
    timeout: int,
    retries: int,
    json_retries: int,
    sem: asyncio.Semaphore,
    image_detail: str,
    api_endpoint: str,
    validate: Callable[[dict[str, Any] | None], str],
    system_prompt: str = JUDGE_SYSTEM,
    rendered_caption: str = "Submitted rendered multi-view image(s) to score:",
    label_root: Path | None = None,
    rendered_image_groups: list[tuple[str, str, list[Path]]] | None = None,
    kind: str = "judge",
) -> tuple[str | None, dict[str, Any] | None, dict[str, Any]]:
    attempts = max(1, json_retries)
    invalid_attempts: list[dict[str, Any]] = []
    prompt = user_text
    last_raw: str | None = None
    last_parsed: dict[str, Any] | None = None

    for attempt in range(attempts):
        raw = await call_gpt55(
            user_text=prompt,
            reference_image_paths=reference_image_paths,
            rendered_image_paths=rendered_image_paths,
            model=model,
            api_key=api_key,
            max_tokens=max_tokens,
            timeout=timeout,
            retries=retries,
            sem=sem,
            image_detail=image_detail,
            api_endpoint=api_endpoint,
            system_prompt=system_prompt,
            rendered_caption=rendered_caption,
            label_root=label_root,
            rendered_image_groups=rendered_image_groups,
        )
        last_raw = raw
        last_parsed = parse_json_obj(raw)
        error = validate(last_parsed)
        if not error:
            return raw, last_parsed, {
                "kind": kind,
                "json_ok": True,
                "json_attempts": attempt + 1,
                "invalid_json_attempts": invalid_attempts,
            }

        invalid_attempts.append(
            {
                "attempt": attempt + 1,
                "error": error,
                "raw_preview": raw_preview(raw),
            }
        )
        log.warning("%s JSON invalid attempt=%d/%d: %s", kind, attempt + 1, attempts, error)
        prompt = (
            user_text
            + "\n\n# Output Correction\n"
            + f"Your previous {kind} answer was invalid: {error}.\n"
            + "Return ONLY one valid JSON object matching the required schema. "
            + "Do not include markdown fences, commentary, or trailing text. "
            + "Include every required id exactly once."
        )

    return last_raw, last_parsed, {
        "kind": kind,
        "json_ok": False,
        "json_attempts": attempts,
        "invalid_json_attempts": invalid_attempts,
    }


