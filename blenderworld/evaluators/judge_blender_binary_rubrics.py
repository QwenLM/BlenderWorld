class AgentContentRefusal(RuntimeError):
    """The agent's explicit upstream rejection must not fall back to another judge."""


def load_agent_verdicts(task_dir: Path, agent_verdict_dir: str) -> dict[str, int]:
    """Read a prior agent-as-judge ``judgement.json`` into ``{rubric_id: 0/1}``.

    Returns an empty dict on any miss (file absent, unparseable, or no rubric_scores)
    so callers can gracefully fall back to VLM scoring for the affected rubrics."""
    path = output_path(task_dir, agent_verdict_dir)
    if not path.exists():
        return {}
    try:
        obj = json.loads(path.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return {}
    if obj.get("agent_error") == "agent_judge_upstream_content_policy_violation":
        raise AgentContentRefusal(obj["agent_error"])
    # Post-check: never trust (leak) the verdicts of an agent-as-judge run that did not cleanly
    # complete. `ok` is False when any scored rubric id is missing/unparseable; `agent_error` is
    # set on timeout / crash / no-raw / parse-failure / (in visual mode) no-render. In either case
    # drop ALL of this run's verdicts so the affected rubrics fall back to VLM scoring instead of
    # being silently forced to a stale/partial 0/1.
    if not obj.get("ok", False):
        log.warning(
            "[evidence-routing] agent judgement %s not ok (%s) — dropping its verdicts; "
            "rubrics fall back to VLM", path, str(obj.get("error") or "")[:200]
        )
        return {}
    agent_err = str(obj.get("agent_error") or "").strip()
    if agent_err:
        log.warning(
            "[evidence-routing] agent judgement %s has agent_error (%s) — dropping its verdicts; "
            "rubrics fall back to VLM", path, agent_err[:200]
        )
        return {}
    out: dict[str, int] = {}
    for item in (obj.get("rubric_scores") or []):
        if not isinstance(item, dict):
            continue
        rid = str(item.get("id", "")).strip()
        if not rid:
            continue
        score = item.get("score")
        if score in (0, "0", "0.0", False):
            out[rid] = 0
        elif score in (1, "1", "1.0", True):
            out[rid] = 1
    return out


