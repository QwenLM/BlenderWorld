def _clamp_dimensions(image: Any, max_dim: int = MAX_IMAGE_DIMENSION) -> Any:
    width, height = image.size
    if width <= max_dim and height <= max_dim:
        return image
    scale = min(max_dim / width, max_dim / height)
    return image.resize((int(width * scale), int(height * scale)), Image.LANCZOS)


def _compress_image_to_jpeg_bytes(
    image: Any,
    max_bytes: int = MAX_IMAGE_BYTES,
    max_dim: int = MAX_IMAGE_DIMENSION,
    quality_ladder: tuple[int, ...] = (90, 80, 70, 60, 45, 30),
    scale_ladder: tuple[float, ...] = (0.75, 0.5, 0.35, 0.25),
) -> bytes:
    """Encode a PIL image to JPEG bytes fitting max_bytes. Walks quality_ladder at
    full (clamped) resolution first and returns the highest quality that fits; only
    if none fit does it fall back to scale_ladder downscaling. Callers that must
    preserve resolution (e.g. the media-OSS presigned path) pass a huge max_dim and
    a high-quality ladder so downscaling is an effectively unreachable last resort."""
    if image.mode == "P" and "transparency" in image.info:
        image = image.convert("RGBA")
    if image.mode in ("RGBA", "LA"):
        rgba = image.convert("RGBA")
        if rgba.getchannel("A").getextrema()[0] < 255:
            # Display the original alpha over a neutral checkerboard before JPEG
            # encoding. Dropping alpha silently turns transparency into black.
            from PIL import ImageDraw
            background = Image.new("RGBA", rgba.size, (224, 224, 224, 255))
            draw = ImageDraw.Draw(background)
            cell = max(8, max(rgba.size) // 32)
            for y in range(0, rgba.height, cell):
                for x in range(0, rgba.width, cell):
                    if (x // cell + y // cell) % 2:
                        draw.rectangle((x, y, x + cell - 1, y + cell - 1), fill=(160, 160, 160, 255))
            image = Image.alpha_composite(background, rgba).convert("RGB")
        else:
            image = rgba.convert("RGB")
    elif image.mode == "P":
        image = image.convert("RGB")
    image = _clamp_dimensions(image, max_dim=max_dim)

    for quality in quality_ladder:
        buffer = io.BytesIO()
        image.save(buffer, format="JPEG", quality=quality, optimize=True)
        if buffer.tell() <= max_bytes:
            return buffer.getvalue()

    for scale in scale_ladder:
        resized = image.resize((max(1, int(image.width * scale)), max(1, int(image.height * scale))), Image.LANCZOS)
        buffer = io.BytesIO()
        resized.save(buffer, format="JPEG", quality=60, optimize=True)
        if buffer.tell() <= max_bytes:
            return buffer.getvalue()

    buffer = io.BytesIO()
    image.resize((max(1, image.width // 4), max(1, image.height // 4)), Image.LANCZOS).save(
        buffer,
        format="JPEG",
        quality=30,
        optimize=True,
    )
    return buffer.getvalue()


def _compress_image_to_base64(image: Any, max_bytes: int = MAX_IMAGE_BYTES) -> str:
    return base64.b64encode(_compress_image_to_jpeg_bytes(image, max_bytes=max_bytes)).decode("ascii")


def image_to_data_url(path: Path, max_bytes: int = MAX_IMAGE_BYTES) -> str | None:
    if not path.exists():
        return None
    if Image is not None:
        try:
            b64 = _compress_image_to_base64(Image.open(path), max_bytes=max_bytes)
            return f"data:image/jpeg;base64,{b64}"
        except Exception as exc:  # noqa: BLE001
            log.warning("failed to compress image %s: %s; falling back to raw data URL", path, exc)
    try:
        raw = path.read_bytes()
    except OSError:
        return None
    if len(raw) > max_bytes:
        log.warning(
            "skipping image %s because Pillow is unavailable/failed and raw size %.1f MB exceeds %.1f MB",
            path,
            len(raw) / 1024 / 1024,
            max_bytes / 1024 / 1024,
        )
        return None
    mime = mimetypes.guess_type(str(path))[0] or "image/png"
    b64 = base64.b64encode(raw).decode("ascii")
    return f"data:{mime};base64,{b64}"


