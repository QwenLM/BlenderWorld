def load_rubric_results(path: Path) -> list[dict[str, Any]]:
    obj = json.loads(path.read_text(encoding="utf-8"))
    results = obj.get("results")
    if not isinstance(results, list):
        raise ValueError(f"missing results list in {path}")
    return results


def task_name(task_dir: Path) -> str:
    return task_dir.name.rstrip("/")


def find_reference_images(task_dir: Path, pattern: str, max_images: int) -> list[Path]:
    images = [p for p in task_dir.glob(pattern) if p.is_file()]
    images = sorted(images, key=lambda path: str(path))
    if max_images > 0:
        images = images[:max_images]
    return images


def find_render_images(task_dir: Path, pattern: str, max_images: int) -> list[Path]:
    images = [p for p in task_dir.glob(pattern) if p.is_file() and p.suffix.lower() in IMAGE_SUFFIXES]

    def key(path: Path) -> tuple[int, str]:
        stem = path.stem
        try:
            rank = VIEW_ORDER.index(stem)
        except ValueError:
            rank = len(VIEW_ORDER)
        return rank, str(path)

    images = sorted(images, key=key)
    if max_images > 0:
        images = images[:max_images]
    return images


def dedupe_paths(paths: list[Path]) -> list[Path]:
    seen: set[str] = set()
    out: list[Path] = []
    for path in paths:
        key = str(path.resolve())
        if key in seen:
            continue
        seen.add(key)
        out.append(path)
    return out


def parse_glob_list(value: str | list[str] | tuple[str, ...]) -> list[str]:
    # Repeated --extra-image-glob flags arrive as a list, and each flag may
    # itself contain comma-separated patterns (as main.sh passes them).
    values = [value] if isinstance(value, str) else value
    return [part.strip() for item in values for part in item.split(",") if part.strip()]


# Directories whose images are texture / material / thumbnail / cache assets,
# i.e. inputs or intermediates, not deliverable scene renders.
AUX_DIR_NAMES = {
    "_tex", "tex", "texture", "textures", "_textures", "tex_maps", "texmaps",
    "maps", "_maps", "matcap", "matcaps", "material", "materials",
    "thumb", "thumbs", "thumbnail", "thumbnails", "_thumbnails",
    "cache", "_cache", "bake", "_bake", "baked", "hdri", "_hdri", "hdris",
    "lightmaps", "uv", "uvs", "mask", "masks", "alpha", "alphas",
    "preview", "previews", "_preview", "_previews",
}
# Filename prefixes that indicate PBR texture maps rather than scene renders.
AUX_NAME_PREFIXES = ("tex_", "texture_", "mat_", "material_", "uv_", "mask_")
AUX_NAME_TOKENS = {
    "albedo", "ambientocclusion", "ao", "basecolor", "base_color", "bump",
    "diffuse", "displacement", "disp", "emission", "gloss", "height",
    "metallic", "metalness", "normal", "normalgl", "normaldx", "opacity",
    "roughness", "specular", "transmission", "uv", "uvmap",
}
# Filename tokens that mark denoise / render-debug DIAGNOSTIC images
# (e.g. `_cycles_diag.png`, `_cycles_oidn_volume_diag.png`): intermediate
# noise/denoise debug renders, never scene deliverables, so they must never
# consume an extra-image slot. Kept deliberately narrow so real deliverable names
# are unaffected: no generic engine words like "cycles", and NO ordinary scene
# words. In particular "noisy" (e.g. noisy_market_4k.png) and "aov" (aov_beauty.png)
# were dropped — they are plausible descriptive deliverable names and matched as
# exact tokens, so they risked filtering real heroes; the debug renders they
# targeted are already "_"-prefixed and demoted by is_intermediate_name anyway.
# The retained tokens describe OpenImageDenoise/AOV-debug passes specifically.
AUX_DIAGNOSTIC_TOKENS = {"diag", "oidn", "denoise"}
# Absolute ceiling on extra submission images even when a task exports more real
# deliverables than max_images (adaptive-cap safety valve): keeps the VLM prompt
# bounded while guaranteeing every hero deliverable of a normal submission is shown.
EXTRA_IMAGE_HARD_CEILING = 10
# A same-directory numeric run this long or longer is treated as an animation
# sequence and down-sampled, so its earliest frames cannot fill the cap and
# crowd out the real deliverable (e.g. the final assembled frame).
SEQUENCE_MIN_LEN = 8
# Representative frames kept per large sequence (evenly spaced, always including
# the first and the last / final-result frame). Chosen so a borderline sequence
# keeps about as many frames as the old first-N cap while still surfacing the
# final result rather than only the opening frames.
SEQUENCE_SAMPLE = 6


def is_auxiliary_image(path: Path, root: Path) -> bool:
    """True for texture/material/thumbnail/cache assets that are not renders."""
    try:
        rel_parts = path.relative_to(root).parts
    except ValueError:
        rel_parts = path.parts
    for part in rel_parts[:-1]:
        if part.lower() in AUX_DIR_NAMES:
            return True
    name = path.name.lower()
    if name.startswith(AUX_NAME_PREFIXES):
        return True
    stem = path.stem.lower()
    tokens = {part for part in re.split(r"[^a-z0-9]+", stem) if part}
    if tokens & AUX_NAME_TOKENS:
        return True
    # Denoise / render-debug diagnostic intermediates (e.g. `_cycles_diag`,
    # `_cycles_oidn_volume_diag`) are never scene deliverables.
    return bool(tokens & AUX_DIAGNOSTIC_TOKENS)


def sequence_key(path: Path) -> tuple[str, int] | None:
    """For a frame like frame_0007, return (group_id, 7); else None. group_id
    ties frames sharing a directory and stem prefix (frame_0001..frame_0185)."""
    stem = path.stem
    i = len(stem)
    while i > 0 and stem[i - 1].isdigit():
        i -= 1
    if i == len(stem):
        return None
    try:
        num = int(stem[i:])
    except ValueError:
        return None
    return (str(path.parent) + "::" + stem[:i], num)


def sample_indices(n: int, k: int) -> list[int]:
    """Evenly spaced indices over [0, n-1], inclusive of first and last."""
    if k >= n:
        return list(range(n))
    if k <= 1:
        return [n - 1]
    return sorted({round(i * (n - 1) / (k - 1)) for i in range(k)})


def is_intermediate_name(path: Path) -> bool:
    """True for render-agent intermediates/previews that use the leading-underscore
    convention (e.g. `_preview_autumn.png`, `_cycles_diag.png`). These are real (or
    degraded/preview) images but must rank BELOW proper deliverables so they can
    never crowd a hero render out of a capped extra-image slot. A leading `_` is the
    render agents' consistent marker for hidden/intermediate outputs; genuine
    deliverables are letter-prefixed (autumn_main_4k, dragon_treasure_cave_preview),
    so this deliberately keys on the PREFIX, not a `preview`/`diag` substring."""
    return path.name.startswith("_")


def extra_image_sort_key(path: Path) -> tuple[int, int, int, str, int]:
    """Sort order for extra submission images (most-important first):
      1. priority   — real deliverables (0) before `_`-prefixed intermediates (1).
      2. depth      — shallower paths first.
      3. kind       — standalone renders (0) before sequence samples (1), so a lone
                      hero deliverable can never be pushed past sampled frames.
      4. tie-break  — alphabetical path (standalone) or sequence group id.
      5. frame no.  — numeric-aware ordering within a sequence.
    The leading priority tier is what stops `_`-prefixed previews and denoise
    diagnostics from sorting ahead of hero deliverables under a plain alphabetical
    tie (ASCII `_` (0x5F) < letters), which previously let them fill every capped
    slot and exclude the real *_main_4k renders."""
    priority = 1 if is_intermediate_name(path) else 0
    seq = sequence_key(path)
    depth = len(path.parts)
    if seq is not None:
        return (priority, depth, 1, seq[0], seq[1])
    return (priority, depth, 0, str(path).lower(), -1)


def find_extra_submission_images(task_dir: Path, patterns: str | list[str], max_images: int) -> list[Path]:
    images: list[Path] = []
    for pattern in parse_glob_list(patterns):
        images.extend(
            path
            for path in task_dir.glob(pattern)
            if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES
        )
    images = dedupe_paths(images)
    input_manifest = task_dir / "input_media_sha256.json"
    if input_manifest.exists():
        input_hashes = set(json.loads(input_manifest.read_text()))
        images = [p for p in images if hashlib.sha256(p.read_bytes()).hexdigest() not in input_hashes]
    if not images:
        return []

    # Keep deliverable renders; input textures are not author-rendered evidence.
    filtered = [path for path in images if not is_auxiliary_image(path, task_dir)]

    if max_images <= 0:
        return dedupe_paths(sorted(filtered, key=extra_image_sort_key))

    # Collapse large numeric frame sequences to evenly-spaced representatives
    # (always including the final frame) so early frames cannot crowd out the
    # real deliverable when the cap is applied.
    groups: dict[str, list[Path]] = {}
    standalone: list[Path] = []
    for path in filtered:
        seq = sequence_key(path)
        if seq is None:
            standalone.append(path)
        else:
            groups.setdefault(seq[0], []).append(path)

    selected: list[Path] = list(standalone)
    for members in groups.values():
        members.sort(key=lambda path: sequence_key(path)[1])
        if len(members) >= SEQUENCE_MIN_LEN:
            selected.extend(members[i] for i in sample_indices(len(members), SEQUENCE_SAMPLE))
        else:
            selected.extend(members)

    # Deliverables first, `_`-prefixed intermediates/previews after; then cap.
    # Adaptive cap: guarantee every real deliverable (priority-0, non-underscore)
    # is kept even if there are more of them than max_images, so a multi-hero
    # submission (e.g. autumn/winter/close-up 4K renders) is never truncated below
    # its deliverable count. Intermediates and sequence samples then fill any
    # remaining slots, all bounded by EXTRA_IMAGE_HARD_CEILING.
    selected = dedupe_paths(sorted(selected, key=extra_image_sort_key))
    # max_images > 0 is guaranteed here (the <= 0 case returned early above).
    deliverable_count = sum(1 for path in selected if not is_intermediate_name(path))
    effective_max = min(EXTRA_IMAGE_HARD_CEILING, max(max_images, deliverable_count))
    selected = selected[:effective_max]
    return selected


def find_animation_frames(task_dir: Path, patterns: str | list[str], max_images: int) -> list[Path]:
    """Collect time-ordered animation frames (sampled upstream by main.sh from the
    model's exported video) under .eval_workspace/anim_frames. Unlike
    find_extra_submission_images these are NOT re-downsampled — main.sh already
    picked an evenly-spaced set — they are only ordered by (group, frame number)
    via extra_image_sort_key and capped at max_images."""
    images: list[Path] = []
    for pattern in parse_glob_list(patterns):
        images.extend(
            path
            for path in task_dir.glob(pattern)
            if path.is_file() and path.suffix.lower() in IMAGE_SUFFIXES
        )
    images = dedupe_paths(images)
    if not images:
        return []
    images = sorted(images, key=extra_image_sort_key)
    if max_images > 0:
        images = images[:max_images]
    return images


def output_path(task_dir: Path, output_dir: str) -> Path:
    out = Path(output_dir)
    if out.is_absolute():
        return out / task_name(task_dir) / "judgement.json"
    return task_dir / out / "judgement.json"


def is_complete_judgement(path: Path, rubric_ids: set[str]) -> bool:
    if not path.exists():
        return False
    try:
        obj = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return False
    if not obj.get("ok"):
        return False
    scores = obj.get("rubric_scores")
    if not isinstance(scores, list):
        return False
    seen = {str(item.get("id")) for item in scores if isinstance(item, dict)}
    if seen != rubric_ids:
        return False
    return all(item.get("score") in (0, 1) for item in scores if isinstance(item, dict))


